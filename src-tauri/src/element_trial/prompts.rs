//! LLM Prompts for 要素式审判智能辅助(2026-06-22)
//!
//! 三大核心 prompt:
//! - generate_complaint: 庭审前要素式诉辩状生成
//! - analyze_facts: 庭审中要件事实分析研判
//! - build_strategy: 攻防策略生成

/// 庭审前:要素式起诉状/答辩状智能生成
///
/// 输入:案件基本信息 + 案由要素模板 + 已有文档摘要
/// 输出:要素式起诉状或答辩状 Markdown
pub fn generate_complaint_prompt(
    case_summary_json: &str,
    templates_json: &str,
    doc_type: &str, // 起诉状 or 答辩状
) -> String {
    let role_instruction = match doc_type {
        "起诉状" => "你是一名资深原告代理律师,需要基于已知案件事实和要素模板,撰写一份要素式起诉状。",
        "答辩状" => "你是一名资深被告代理律师,需要基于已知案件事实和要素模板,撰写一份要素式答辩状。",
        _ => "你是一名资深诉讼律师,需要撰写一份要素式法律文书。",
    };

    format!(
        r#"## 角色

{role_instruction}

## 任务

请严格遵循以下要素式模板,为指定案件撰写一份结构完整、事实清晰的{doc_type}。每一要素必须基于「已知案件信息」填写;若某项要素尚无对应事实,标注「[待补充]」并在末尾列出待补充清单。

## 格式要求

1. 输出为 Markdown,标题使用 ##
2. 按要素顺序逐项撰写,每个要素一个小节
3. 每个要素包含:事实陈述 + 对应证据索引
4. 如有金额计算项(赔偿项目),以表格呈现
5. 末尾附「待补充材料清单」

## 案件信息

{case_summary_json}

## 案由要素模板

{templates_json}

## 输出

请直接输出{doc_type}正文,不要额外解释。"#
    )
}

/// 庭审中:要件事实分析研判
///
/// 输入:案件已提交材料摘要 + 要素模板 + 已识别的要件事实
/// 输出:逐条要件分析(证据归依、举证状态、争点判断、法院认定预测)
pub fn analyze_facts_prompt(
    case_summary_json: &str,
    templates_json: &str,
    materials_json: &str,
) -> String {
    format!(
        r#"## 角色

你是一名资深审判法官,具有丰富的要件事实审理经验。请基于案件材料,按照要素式审判方法论,逐项分析要件事实。

## 任务

对以下案件的要件事实进行逐项研判,使用"证据→要件→争点"三重归依模型:

1. **要件事实归依**:每个要件对应哪些证据,举证是否充分
2. **证明力评估**:各证据的证明力强度(强/中/弱/无)
3. **争点识别**:双方是否存在实质性争议,标注争点
4. **法院认定预测**:基于现有证据,预测法院对该要件可能的事实认定结论

## 输出格式

对每个要件输出:

- 要件名称
- 主张方
- 举证状态(pending/已举证/待补证/举证不能)
- 关联证据列表
- 证明力评估
- 对方抗辩(如有)
- 法院认定预测
- 是否构成争点

## 案件信息

{case_summary_json}

## 案由要素模板

{templates_json}

## 各方已提交材料摘要

{materials_json}

## 输出

请直接输出要件事实分析表,每项用 --- 分隔,最后附「争点汇总」和「关键证据缺口」。"#
    )
}

/// 庭审中:攻防策略生成(三级递进模型)
///
/// 输入:争点列表 + 要件事实 + 证据状态
/// 输出:三级递进攻防策略 + 抗辩预判 + 建议取证动作
pub fn build_strategy_prompt(
    case_summary_json: &str,
    disputed_facts_json: &str,
    our_side: &str,
) -> String {
    format!(
        r#"## 角色

你是一名顶尖诉讼策略顾问,精通诉讼攻防方法论。你需要为代理方({our_side})制定庭审攻防策略。

## 方法论:三级递进模型

### 第一层:主张责任分析
- 我方需要主张什么?法律依据是什么?
- 对方可能主张什么?其法律依据强度如何?

### 第二层:证明责任分析
- 各要件的证明责任归属
- 举证难度评估(易/中/难)
- 现有证据是否满足证明标准

### 第三层:举证行为策略
- 已有哪些证据,还缺什么
- 补证优先级排序
- 证据链构建路径

## 输出格式

对每个争点输出:

1. **争点描述**
2. **主张责任分析**(我方主张 / 对方主张 / 法律依据)
3. **证明责任分析**(归属 / 难度 / 现有证据评估)
4. **举证策略**(已有证据 / 证据缺口 / 建议取证动作 / 优先级)
5. **对方抗辩预判**(对方可能的抗辩路径及应对)
6. **风险评估**(高/中/低)
7. **庭审攻防要点**(询问提纲 / 质证要点 / 辩论焦点)

## 案件信息

{case_summary_json}

## 当前争点与要件事实

{disputed_facts_json}

## 输出

请直接输出攻防策略,按争点逐个分析,最后附「整体策略建议」和「风险提示」。"#
    )
}

/// 案由自动识别 prompt(基于案件名称 + 文档内容)
pub fn identify_cause_prompt(case_name: &str, doc_extracts: &str) -> String {
    format!(
        r#"## 任务

根据案件名称和材料摘要,识别本案的案由。请从最高人民法院《民事案件案由规定》中选择最匹配的案由。

## 案件名称
{case_name}

## 材料摘要
{doc_extracts}

## 输出

输出 JSON:
{{
  "cause": "案由全称",
  "confidence": "高/中/低",
  "reasoning": "匹配依据(30字以内)"
}}
"#
    )
}
